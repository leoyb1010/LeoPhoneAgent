export function currentAppVersion(): string {
  // Vite 在构建时注入;取不到就当作未知,不弹卡(宁可不弹,不要误弹)
  return (import.meta.env?.VITE_APP_VERSION as string) || '';
}

/** 版本变了返回 true。看完才记账,所以这里不写入。 */
export function shouldShowWhatsNew(): boolean {
  try {
    return shouldShowWhatsNewFor(currentAppVersion(), (key) => localStorage.getItem(key));
  } catch {
    return false;
  }
}

export function markWhatsNewSeen(): void {
  markWhatsNewSeenFor(currentAppVersion(), (key, value) => { localStorage.setItem(key, value); });
}

export function currentReleaseNote(): LeoReleaseNote | null {
  return releaseNoteForVersion(LEO_RELEASE_NOTES, currentAppVersion());
}
