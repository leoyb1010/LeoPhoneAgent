#!/usr/bin/env python3
"""Single maintained source for .github/workflows/harmony-protocol.yml.

Edit THIS file, then run:
    python3 scripts/HarmonyCIWorkflow.py --write    # regenerate the workflow
    python3 scripts/HarmonyCIWorkflow.py --check    # exit 1 unless the file is byte-identical

Why a generator instead of parsing YAML: a lenient parser or substring search
cannot prove a job is active (if: false, continue-on-error, echo-only gates,
quoted or duplicate keys, runner groups, dispatch-only triggers all look
"present"). The workflow is owned by this repo, so the audit requires the
committed file to equal the generated text exactly; any hand edit fails closed.
Standard library only; no YAML dependency on Pro or CI.
"""
import argparse
import sys
from pathlib import Path

WORKFLOW_REL = ".github/workflows/harmony-protocol.yml"

# actions/checkout v4.4.0 and actions/setup-node v4.4.0: refs/tags/v4 -> commit,
# verified through the official GitHub refs API (Pro, 2026-11-10).
CHECKOUT = "actions/checkout@11d5960a326750d5838078e36cf38b85af677262"
SETUP_NODE = "actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020"
NODE_VERSION = "24.14.0"  # official release; ships node:module stripTypeScriptTypes
RUNNER = "ubuntu-latest"  # GitHub-hosted. Public PRs must never reach self-hosted runners.

TRIGGER_PATHS = (
    "src/**",
    "scripts/**",
    ".github/workflows/**",
    "README.md",
    "CHANGELOG.md",
)

PREFLIGHT = (
    "node -e 'const [a,b]=process.versions.node.split(\".\").map(Number); "
    "if (a<22||(a===22&&b<13)) { console.error(\"Node \"+process.versions.node+\" lacks stripTypeScriptTypes\"); process.exit(1) }'",
    "node -e 'if (typeof require(\"node:module\").stripTypeScriptTypes !== \"function\") process.exit(1)'",
    "test -x /usr/bin/python3",
    "files=(src/harmony/protocol/*.test.mjs)",
    "[ \"${#files[@]}\" -gt 0 ]",
    "echo \"Harmony protocol test files: ${#files[@]}\"",
)

# Trusted constant shell commands (globs intentionally unquoted).
CHECKS = (
    "node --test src/harmony/protocol/*.test.mjs",
    "node src/harmony/scripts/check_ui_tokens.mjs",
    "bash src/harmony/scripts/verify_harmony_release_notes.sh",
    "python3 scripts/HarmonyCIWorkflow.py --check",
    "python3 scripts/RepositoryEntryPointAudit.py",
    "python3 scripts/RepositoryEntryPointAuditTests.py",
)


def render_run_script(checks=CHECKS, preflight=PREFLIGHT):
    """Bash body of the gate step. Every check runs; exit = first failing rc."""
    lines = [
        "set -euo pipefail",
        "shopt -s failglob",
        *preflight,
        "first_rc=0",
        "run_check() {",
        "  echo \"::group::$*\"",
        "  local rc=0",
        "  \"$@\" || rc=$?",
        "  if [ \"$rc\" -eq 0 ]; then",
        "    echo \"Check passed: $*\"",
        "  else",
        "    echo \"::error::Check failed (exit $rc): $*\"",
        "    if [ \"$first_rc\" -eq 0 ]; then first_rc=$rc; fi",
        "  fi",
        "  echo \"::endgroup::\"",
        "}",
        *(f"run_check {c}" for c in checks),
        "echo \"Harmony gates finished; first failing exit: $first_rc\"",
        "exit \"$first_rc\"",
    ]
    return "\n".join(lines) + "\n"


def render_workflow():
    paths = "".join(f"      - '{p}'\n" for p in TRIGGER_PATHS)
    body = "".join(f"          {l}\n" if l else "\n" for l in render_run_script().splitlines())
    return (
        "# GENERATED by scripts/HarmonyCIWorkflow.py - do not edit by hand.\n"
        "# Change the generator, then: python3 scripts/HarmonyCIWorkflow.py --write\n"
        "# Source-level HarmonyOS gates only (no DevEco, HAP build, signing or device).\n"
        "name: HarmonyOS Protocol\n"
        "on:\n"
        "  push:\n"
        "    branches: [main]\n"
        "    paths:\n" + paths +
        "  pull_request:\n"
        "    branches: [main]\n"
        "    paths:\n" + paths +
        "  workflow_dispatch:\n"
        "permissions:\n"
        "  contents: read\n"
        "jobs:\n"
        "  harmony-protocol-tests:\n"
        "    name: HarmonyOS protocol, UI tokens and release notes\n"
        f"    runs-on: {RUNNER}\n"
        "    timeout-minutes: 15\n"
        "    steps:\n"
        f"      - uses: {CHECKOUT}\n"
        "        with:\n"
        "          persist-credentials: false\n"
        f"      - uses: {SETUP_NODE}\n"
        "        with:\n"
        f"          node-version: {NODE_VERSION}\n"
        "      - name: Run Harmony gates\n"
        "        shell: bash\n"
        "        run: |\n" + body
    )


def check(root):
    """Return a list of problems; empty means the committed workflow is the generated one."""
    path = Path(root) / WORKFLOW_REL
    try:
        actual = path.read_bytes()
    except OSError as exc:
        return [f"missing {WORKFLOW_REL}: {exc.strerror}"]
    expected = render_workflow().encode("utf-8")
    if actual == expected:
        return []
    a, e = actual.decode("utf-8", "replace").splitlines(), expected.decode().splitlines()
    for i in range(max(len(a), len(e))):
        got = a[i] if i < len(a) else "<EOF>"
        want = e[i] if i < len(e) else "<EOF>"
        if got != want:
            return [f"{WORKFLOW_REL} differs from scripts/HarmonyCIWorkflow.py output at line {i + 1}: "
                    f"got {got!r}, want {want!r} (edit the generator and run --write)"]
    return [f"{WORKFLOW_REL} differs from generator output (whitespace/line endings)"]


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--print-run-script", action="store_true")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    if args.print_run_script:
        sys.stdout.write(render_run_script())
        return 0
    if args.write:
        target = args.root / WORKFLOW_REL
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_workflow(), encoding="utf-8", newline="\n")
        print(f"HarmonyCIWorkflow: wrote {WORKFLOW_REL}")
        return 0
    problems = check(args.root)
    for p in problems:
        print(f"HarmonyCIWorkflow: FAIL {p}", file=sys.stderr)
    if not problems:
        print(f"HarmonyCIWorkflow: OK {WORKFLOW_REL} matches generator")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
